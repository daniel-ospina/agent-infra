// test-sanctioned-identity.mjs — #2332: the sanctioned-script exemption must key
// on the script's IDENTITY, not on the literal path it happens to be spelled at.
//
// THE DEFECT THIS PINS. `SANCTIONED_SCRIPT_RELPATHS` is resolved under
// `_frameworkRoot` = the directory this MODULE was loaded from, and the check was
// a realpath STRING EQUALITY. That is correct only where the guard and the
// scripts live in ONE tree. pi's deployment does not guarantee that:
// on a copy-deployed box (this cell) the module root is `~/.pi/agent`, whose
// `scripts/` was a PARTIAL copy that did not contain `admin-merge.sh` (#2176),
// while the rail's real home is `$AGENT_INFRA_PATH/scripts/admin-merge.sh`. So
// the comparison compared
//     /tmp/cell-ai/scripts/admin-merge.sh      (executed)
//   ≠ /tmp/cell-home/.pi/agent/scripts/admin-merge.sh   (did not exist)
// and the rail — the chokepoint that computes the failing set before an `--admin`
// merge — was REFUSED from every hub-rooted session (#2332, measured 2026-10-22).
// ⛔ `(did not exist)` is HISTORICAL: as of #3531 the rail is a `merge_gate_srcs`
// member and IS farmed flat to `$DEST/scripts/admin-merge.sh`, so the fixture below
// builds the PRE-#3531 shape deliberately. The identity property this file pins is
// unchanged — the exemption must key on bytes, not on the spelling — and the fixture
// stays valid because a farm can be older than the module that reads it. What changes
// is only which real box the shape describes: today it is an un-refreshed farm, not
// the normal copy-deployed one.
//
// WHAT IS ASSERTED. Exempt iff (a) the file IS at a sanctioned relpath inside a
// framework checkout AND (b) its bytes ARE the audited bytes pinned in
// `sanctioned-scripts.pin.json`. The suite proves each half is load-bearing by
// MUTATING the shipped source into a temp deployment and asserting the inverted
// outcome — a test that cannot fail is not a test:
//
//   (a) sanctioned rail via the COPY path (module root ≠ scripts root) → ALLOWED
//       MUTATION M1 (restore literal-path equality)          → (a) BLOCKED
//   (b) an UNRELATED script at `scripts/admin-merge.sh` inside a framework tree
//       → BLOCKED            MUTATION M2 (drop the digest)   → (b) ALLOWED
//   (c) the AUDITED BYTES at an arbitrary path (`<hub>/scripts/admin-merge.sh`,
//       the #1485 B5b shape)            → BLOCKED  MUTATION M3 (drop the
//       framework-root check)                                → (c3) ALLOWED
//   (d) the AUDITED leaf beside a REPLACED DELEGATE (`ci_exemption.py`, the
//       rail's own grader) → BLOCKED   MUTATION M4 (closure not verified)
//                                                            → (d) ALLOWED
//   (e) the AUDITED leaf with NO delegates present → BLOCKED
//                                       MUTATION M5 (absent delegate skipped)
//                                                            → (e) ALLOWED
//   (f) the pin is not stale vs this checkout (edits, removals, new helpers) (a stale pin would block the rail,
//       so it is regenerated by the same command that is documented here).
//
// #2818 — WHAT TREE THE FRESHNESS ARM JUDGES. Freshness is a property of a
// COMMIT ("the pin agrees with the bytes beside it"), so the pin and the
// sanctioned surface are both read from ONE tree — never the pin from one side of
// a merge result and the scripts from the other. On a push to `main` that tree is
// the working tree (the default). In a PR job the checkout is GitHub's synthetic
// MERGE of head onto the base tip, whose pin and scripts come from different
// commits; `--ref <rev>` names the commit the change is judged on instead (the PR
// head, wired in ci.yml), which is what makes the verdict independent of how far
// `main` has moved. ⛔ The polarity is unchanged: a change that drifts the surface
// without re-cutting still fails, and one that re-cuts still passes — see
// `test-sanctioned-pin-merge-base.mjs`, which pins all three and the
// merged-tree inversion that produced the treadmill.
//
// Run: node extensions/main-worktree-guard/test-sanctioned-identity.mjs
//      node extensions/main-worktree-guard/test-sanctioned-identity.mjs --ref <rev>
//        └ judge freshness on <rev>'s tree instead of the working tree
//      node extensions/main-worktree-guard/test-sanctioned-identity.mjs --cut
//        └ re-cuts sanctioned-scripts.pin.json from THIS checkout (run it in the
//          same commit that changes any listed script; the freshness check reds
//          otherwise, so a stale pin cannot reach main silently)
