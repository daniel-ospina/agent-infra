// test-sanctioned-identity.mjs — #2332: the sanctioned-script exemption must key
// on the script's IDENTITY, not on the literal path it happens to be spelled at.
//
// THE DEFECT THIS PINS. `SANCTIONED_SCRIPT_RELPATHS` is resolved under
// `_frameworkRoot` = the directory this MODULE was loaded from, and the check was
// a realpath STRING EQUALITY. That is correct only where the guard and the
// scripts live in ONE tree. pi's deployment does not guarantee that:
// on a copy-deployed box (this cell) the module root is `~/.pi/agent`, whose
// `scripts/` is a PARTIAL copy that does not contain `admin-merge.sh` (#2176),
// while the rail's real home is `$AGENT_INFRA_PATH/scripts/admin-merge.sh`. So
// the comparison compared
//     /tmp/cell-ai/scripts/admin-merge.sh      (executed)
//   ≠ /tmp/cell-home/.pi/agent/scripts/admin-merge.sh   (does not exist)
// and the rail — the chokepoint that computes the failing set before an `--admin`
// merge — was REFUSED from every hub-rooted session (#2332, measured 2026-10-22).
//
// WHAT IS ASSERTED. Exempt iff (a) the file IS at a sanctioned relpath inside a
// framework checkout AND (b) its bytes ARE the audited bytes pinned in
// `sanctioned-scripts.pin.json`. The suite proves each half is load-bearing by
// MUTATING the shipped source into a temp deployment and asserting the inverted
// outcome — a test that cannot fail is not a test:
//
//   (a) sanctioned rail via the COPY path (module root ≠ scripts root) → ALLOWED
//       MUTATION M1 (restore literal-path equality)          → (a) BLOCKED
//   (b) an UNRELATED script at `scripts/admin-merge.sh` inside a framework tree
//       → BLOCKED            MUTATION M2 (drop the digest)   → (b) ALLOWED
//   (c) the AUDITED BYTES at an arbitrary path (`<hub>/scripts/admin-merge.sh`,
//       the #1485 B5b shape)            → BLOCKED  MUTATION M3 (drop the
//       framework-root check)                                → (c3) ALLOWED
//   (d) the AUDITED leaf beside a REPLACED DELEGATE (`ci_exemption.py`, the
//       rail's own grader) → BLOCKED   MUTATION M4 (closure not verified)
//                                                            → (d) ALLOWED
//   (e) the AUDITED leaf with NO delegates present → BLOCKED
//                                       MUTATION M5 (absent delegate skipped)
//                                                            → (e) ALLOWED
//   (f) the pin is not stale vs this checkout (edits, removals, new helpers) (a stale pin would block the rail,
//       so it is regenerated by the same command that is documented here).
//
// #2818 — WHAT TREE THE FRESHNESS ARM JUDGES. Freshness is a property of a
// COMMIT ("the pin agrees with the bytes beside it"), so the pin and the
// sanctioned surface are both read from ONE tree — never the pin from one side of
// a merge result and the scripts from the other. On a push to `main` that tree is
// the working tree (the default). In a PR job the checkout is GitHub's synthetic
// MERGE of head onto the base tip, whose pin and scripts come from different
// commits; `--ref <rev>` names the commit the change is judged on instead (the PR
// head, wired in ci.yml), which is what makes the verdict independent of how far
// `main` has moved. ⛔ The polarity is unchanged: a change that drifts the surface
// without re-cutting still fails, and one that re-cuts still passes — see
// `test-sanctioned-pin-merge-base.mjs`, which pins all three and the
// merged-tree inversion that produced the treadmill.
//
// Run: node extensions/main-worktree-guard/test-sanctioned-identity.mjs
//      node extensions/main-worktree-guard/test-sanctioned-identity.mjs --ref <rev>
//        └ judge freshness on <rev>'s tree instead of the working tree
//      node extensions/main-worktree-guard/test-sanctioned-identity.mjs --cut
//        └ re-cuts sanctioned-scripts.pin.json from THIS checkout (run it in the
//          same commit that changes any listed script; the freshness check reds
//          otherwise, so a stale pin cannot reach main silently)
import { execSync } from "node:child_process";
import { copyFileSync, cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { register, registerHooks, stripTypeScriptTypes } from "node:module";
import { closureOf, computePin, diskTree, gitTree, parseRefArg, pinReport, sanctionedPaths } from "./sanctioned-pin-tree.mjs";

const HERE = realpathSync(fileURLToPath(new URL(".", import.meta.url)));
const REPO = realpathSync(join(HERE, "..", ".."));
const PIN_JSON = join(HERE, "sanctioned-scripts.pin.json");
const HOOKS = new URL("./module-load-hooks.mjs", import.meta.url).href;

// `--ref <rev>` selects the COMMIT freshness is judged on (#2818). Absent ⇒ the
// working tree, which is the only correct reading on a push to `main` and on a
// checkout of the change itself. An empty/missing value is an ERROR, never a
// silent fall back to the working tree (`parseRefArg` carries the reasoning).

// A blocked git op, assembled so this file's own text does not carry the
// operation as one literal (the guard would refuse to run its own suite).
const RESET = ["git", "reset", "--hard"].join(" ");

let pass = 0, fail = 0, skip = 0;
function expect(name, got, expected) {
  const ok = JSON.stringify(got) === JSON.stringify(expected);
  console.log(`${ok ? "✅" : "❌"} ${name}: ${JSON.stringify(got)}${ok ? "" : ` (expected ${JSON.stringify(expected)})`}`);
  ok ? pass++ : fail++;
}
function fatal(name, detail) {
  console.log(`❌ ${name}: ${detail}`);
  fail++;
}

let CUT = false;
let REF = null;
try {
  ({ cut: CUT, ref: REF } = parseRefArg(process.argv.slice(2)));
} catch (e) {
  fatal("--ref", String((e && e.message) || e));
  process.exit(1);
}

// ── the TREE the sanctioned surface and the pin are read from ─────────────
// THE #2818 RULE: ONE tree, both sides. `--ref <rev>` names a COMMIT; absent, the
// working tree (a push to `main`, or a checkout of the change itself). Surface,
// closure and pin all come from that same tree, so a merge result — whose pin and
// scripts can come from different commits — can no longer decide the verdict.
let TREE = null;
let TREE_ERROR = null;
try {
  TREE = REF ? gitTree(REPO, REF) : diskTree(REPO);
} catch (e) {
  TREE_ERROR = String((e && e.message) || e);
}
// The sanctioned relpaths are read from the SOURCE, not restated here: a suite
// with its own copy of the list goes green while the shipped list is edited.
const SANCTIONED = TREE_ERROR ? [] : sanctionedPaths(TREE);
// The delegation closure: every file a sanctioned script executes BY ITS OWN
// LOCATION is part of the program that runs, so it is part of the identity
// (`sanctioned-pin-tree.mjs` carries the pattern and the reasoning).
const closure = () => closureOf(TREE, SANCTIONED);

// ── --cut: regenerate the pin from THIS checkout ──────────────────────────
function cut() {
  let doc;
  try {
    doc = computePin(diskTree(REPO), JSON.parse(readFileSync(PIN_JSON, "utf-8"))._why);
  } catch (e) {
    fatal("cut", String((e && e.message) || e));
    return;
  }
  writeFileSync(PIN_JSON, JSON.stringify(doc, null, 2) + "\n");
  console.log(`✅ re-cut ${PIN_JSON.slice(REPO.length + 1)}: ${Object.keys(doc.sha256).length} sanctioned scripts, ${Object.keys(doc.delegates).length} delegates`);
}

if (CUT && REF) {
  fatal("--cut takes no --ref", "--cut writes the pin for the WORKING TREE; pass one or the other");
  process.exit(1);
}
if (CUT) {
  cut();
  process.exit(fail === 0 ? 0 : 1);
}

// ── (f) the pin is not stale, judged on ONE tree (#2818) ──────────────────
console.log(`── (f) pin freshness — pin and sanctioned surface read from ${TREE ? TREE.label : "<unreadable>"} ──`);
if (TREE_ERROR) {
  // A reference the gate cannot read must never report a PASS about some other
  // tree (that is how a pinned gate goes inert) — it is a FAIL that names why.
  fatal("(f) the reference tree is readable", TREE_ERROR);
} else if (!TREE.has("manifest.json")) {
  skip++;
  console.log("⏭️  stale-pin check: SKIPPED — this is a deployed copy, not the framework checkout");
} else {
  let report = null;
  try { report = pinReport(TREE); } catch (e) { fatal("(f) the sanctioned list is readable", String((e && e.message) || e)); }
  if (report && report.parseError) {
    fatal("(d) pin parses", report.parseError);
  } else if (report) {
    const pin = report.pin, dels = report.delegates;
    expect("(d1) every SANCTIONED_SCRIPT_RELPATHS entry is pinned", report.sanctioned.filter((r) => typeof pin[r] !== "string"), []);
    // A REMOVAL is stale too: a PR that deletes a listed script leaves the pin
    // exempting a relpath the framework no longer ships (and the deleted bytes are
    // still in git history), so a missing file reds here rather than skipping.
    expect("(d2) every pinned digest matches the sanctioned surface in the SAME tree (re-cut: node extensions/main-worktree-guard/test-sanctioned-identity.mjs --cut)",
      report.stale, []);
    expect("(d3) every leaf is pinned and the closure covers the leaves too", Object.keys(pin).filter((r) => !report.sanctioned.includes(r)), []);
    expect("(d4) the pin names every file a listed script executes by its own location (a new $SELF_DIR helper ⇒ re-cut)",
      Object.keys(report.closure).filter((r) => typeof dels[r] !== "string"), []);
    expect("(d5) the closure is non-empty (an empty closure is not a verified one)", Object.keys(dels).length > 0, true);
  }
}
// ── the real handler, loaded from a COPY-DEPLOYED module root ─────────────
if (typeof stripTypeScriptTypes !== "function" || (typeof register !== "function" && typeof registerHooks !== "function")) {
  skip++;
  console.log(`⏭️  behavioural arm: SKIPPED — node ${process.versions.node} lacks module.stripTypeScriptTypes (needs >= 22.13)`);
} else {
  const hooks = await import(HOOKS);
  if (typeof registerHooks === "function") registerHooks({ resolve: hooks.resolve, load: hooks.load });
  else register(new URL("./module-load-hooks.mjs", import.meta.url), import.meta.url);
  process.removeAllListeners("warning");

  const work = realpathSync(mkdtempSync(join(tmpdir(), "sanctioned-identity-")));
  const savedEnv = new Map(["HOME", "PI_SESSION_ID", "AGENT_ALLOW_MAIN_EDITS", "ELDATO_ALLOW_MAIN_EDITS"]
    .map((v) => [v, process.env[v]]));

  /** Deploy the guard extension to <root>/extensions/main-worktree-guard (a
   *  COPY, exactly how pi lands it on a cell) and return the module's file URL.
   *  `mutate` is applied to index.ts and MUST match — an unapplied patch fails
   *  loudly instead of silently testing the unmutated code. */
  function deploy(root, mutate = null) {
    const dir = join(root, "extensions", "main-worktree-guard");
    mkdirSync(dir, { recursive: true });
    for (const f of readdirSync(HERE)) {
      if (/\.(ts|mjs|json)$/.test(f) && !f.startsWith("test")) copyFileSync(join(HERE, f), join(dir, f));
    }
    if (mutate) {
      const src = readFileSync(join(dir, "index.ts"), "utf-8");
      if (!src.includes(mutate.from)) { fatal(`mutation ${mutate.name} applies`, `anchor not found in index.ts: ${mutate.from.slice(0, 80)}`); return null; }
      writeFileSync(join(dir, "index.ts"), src.replace(mutate.from, mutate.to));
    }
    // index.ts imports ../shared/* (audit + print-mode) — a deployment carries
    // the whole extensions tree, so the copy has to as well.
    cpSync(join(HERE, "..", "shared"), join(root, "extensions", "shared"), { recursive: true });
    mkdirSync(join(root, ".pi", "agent"), { recursive: true });
    return pathToFileURL(join(dir, "index.ts")).href;
  }

  /** A framework checkout: the fingerprint files arm 2 checks, plus whatever
   *  scripts the caller writes into it. */
  function framework(root) {
    mkdirSync(join(root, "pi-bootstrap"), { recursive: true });
    writeFileSync(join(root, "manifest.json"), "{}\n");
    writeFileSync(join(root, "pi-bootstrap", "setup.sh"), "#!/bin/bash\ntrue\n");
  }

  /** Copy the audited DELEGATION CLOSURE (every file a sanctioned script runs by
   *  its own location) into a fixture root — arm 2 verifies the whole program,
   *  so a root with only the leaf is (correctly) not exempt. */
  function installClosure(root, override = {}) {
    let pin = {};
    try { pin = JSON.parse(readFileSync(PIN_JSON, "utf-8")).delegates ?? {}; } catch { pin = {}; }
    for (const rel of Object.keys(pin)) {
      const dest = join(root, rel);
      mkdirSync(dirname(dest), { recursive: true });
      if (override[rel] !== undefined) writeFileSync(dest, override[rel]);
      else copyFileSync(join(REPO, rel), dest);
    }
    return Object.keys(pin);
  }

  async function loadGuard(root, mutate) {
    const url = deploy(root, mutate);
    if (!url) return null;
    const realWarn = console.warn;
    console.warn = () => {};
    let mod;
    try { mod = await import(url); } finally { console.warn = realWarn; }
    const handlers = new Map();
    mod.default({ on(name, fn) { if (!handlers.has(name)) handlers.set(name, []); handlers.get(name).push(fn); } });
    return handlers.get("tool_call")?.[0] ?? null;
  }

  try {
    // A hermetic HUB (main checkout on main, clean) — the actor in scope: the
    // script gate is a no-op in a linked worktree.
    const hub = join(work, "hub");
    execSync(`git init -q -b main "${hub}"`, { stdio: "ignore" });
    execSync("git config user.email t@t && git config user.name t", { cwd: hub, stdio: "ignore" });
    writeFileSync(join(hub, "clean.txt"), "v1\n");
    execSync("git add -A && git commit -qm init", { cwd: hub, stdio: "ignore" });
    for (const v of ["AGENT_ALLOW_MAIN_EDITS", "ELDATO_ALLOW_MAIN_EDITS"]) delete process.env[v];
    process.env.HOME = join(work, "home");
    delete process.env.PI_SESSION_ID;

    // The FRAMEWORK CHECKOUT the scripts really live in — deliberately a
    // DIFFERENT root from the deployed module root, which is the whole defect.
    const fw = join(work, "framework");
    framework(fw);
    mkdirSync(join(fw, "scripts"), { recursive: true });
    copyFileSync(join(REPO, "scripts", "admin-merge.sh"), join(fw, "scripts", "admin-merge.sh"));
    installClosure(fw);

    const bash = async (toolCall, command, cwd) => {
      const prev = process.cwd();
      process.chdir(cwd);
      try { return await toolCall({ toolName: "bash", input: { command } }, undefined); }
      finally { process.chdir(prev); }
    };
    const allowed = (r) => r === undefined || r === null;
    const blocked = (r) => !!r && r.block === true;
    const RAIL = join(fw, "scripts", "admin-merge.sh");

    const guard = await loadGuard(join(work, "deploy"));
    if (!guard) throw new Error("the deployed guard did not register a tool_call handler");
    expect("B0: the module root is the DEPLOYMENT (not the scripts checkout) — the cell geometry that broke",
      existsSync(join(work, "deploy", "scripts", "admin-merge.sh")), false);

    // ── (a) THE SANCTIONED RAIL, VIA THE COPY PATH → ALLOWED ──
    const railAllowed = allowed(await bash(guard, `bash "${RAIL}" --help`, hub));
    expect("(a) sanctioned rail via a DIFFERENT root from the module's (§admin-merge.sh) → ALLOWED", railAllowed, true);

    // ── (b) AN UNRELATED SCRIPT RENAMED TO THE SANCTIONED RELPATH → BLOCKED ──
    // Same framework tree, same relpath, same filename — only the BYTES differ.
    // This is the half a path rule cannot see, so it is what proves identity.
    const fw2 = join(work, "framework-forged");
    framework(fw2);
    mkdirSync(join(fw2, "scripts"), { recursive: true });
    installClosure(fw2); // a real attack copies the whole farm; only the LEAF differs
    writeFileSync(join(fw2, "scripts", "admin-merge.sh"), `#!/bin/bash\n${RESET}\n`);
    expect("(b) an UNRELATED script at a framework tree's scripts/admin-merge.sh (right name, wrong bytes) → BLOCKED",
      blocked(await bash(guard, `bash "${join(fw2, "scripts", "admin-merge.sh")}" 123`, hub)), true);

    // ── (b3) THE #1228 BODY ARM IS DIGEST-KEYED, NOT PATH-KEYED ──
    // `_sanctionedScriptExemption` arm 1 is PATH ONLY by spec (the pre-existing #1129
    // anchor, deliberately unchanged) and `deploy()` makes its root the MODULE root — so a
    // body planted at `<moduleRoot>/scripts/<sanctioned relpath>` is admitted by arm 1
    // alone. This fixture is exactly that shape and carries a runtime-EXPANDED operand, so
    // the only thing that can refuse it is the digest in `_isAuditedSanctionedScript`. The
    // 2026-10-24 defect: the #1228 refusal was stood down for a sanctioned script's body
    // keyed on the PATH, which made an unaudited file at an audited relpath runnable — the
    // fail-open (an operand the shell resolves at runtime, discarding work the gate never
    // read). M6 below drops the digest and requires this invocation to be ALLOWED, so this
    // arm fails if the key ever becomes the path again.
    const plant = (root) => {
      mkdirSync(join(root, "scripts"), { recursive: true });
      const p = join(root, "scripts", "scratch-worktree.sh");
      writeFileSync(p, '#!/bin/bash\ngrep -qa m <(head -c 10 "$HOME/x")\n');
      return p;
    };
    const planted = plant(join(work, "deploy"));
    const plantedRes = await bash(guard, `bash "${planted}" --help`, hub);
    expect("(b3) unaudited bytes at a SANCTIONED relpath under the MODULE root → BLOCKED (#709: the DIGEST decides, not the path)",
      blocked(plantedRes) && /#709/.test(String(plantedRes.reason)) && /shell-expansion form/.test(String(plantedRes.reason)), true);

    // ── (c) THE AUDITED BYTES AT AN ARBITRARY PATH → BLOCKED (#1485 B5b) ──
    // The pin alone would exempt this; the framework-root half is what does not.
    const hubScripts = join(hub, "scripts");
    mkdirSync(hubScripts, { recursive: true });
    copyFileSync(RAIL, join(hubScripts, "admin-merge.sh"));
    expect("(c) the AUDITED bytes copied into the session repo at scripts/admin-merge.sh → BLOCKED (a pin alone is a content rule)",
      blocked(await bash(guard, "bash scripts/admin-merge.sh 123", hub)), true);
    copyFileSync(RAIL, join(fw, "scripts", "admin-merge-copy.sh"));
    expect("(c2) the AUDITED bytes under a framework tree at a NON-sanctioned relpath → BLOCKED",
      blocked(await bash(guard, `bash "${join(fw, "scripts", "admin-merge-copy.sh")}" 123`, hub)), true);
    // The root check's own load-bearing case: leaf + FULL closure, but the
    // directory is not a framework checkout (no fingerprint files).
    const plain = join(work, "not-a-framework");
    framework(plain);
    rmSync(join(plain, "manifest.json"), { force: true });
    rmSync(join(plain, "pi-bootstrap"), { recursive: true, force: true });
    mkdirSync(join(plain, "scripts"), { recursive: true });
    copyFileSync(RAIL, join(plain, "scripts", "admin-merge.sh"));
    installClosure(plain);
    expect("(c3) the AUDITED leaf + FULL closure in a directory that is NOT a framework checkout → BLOCKED (the root check confines the exemption)",
      blocked(await bash(guard, `bash "${join(plain, "scripts", "admin-merge.sh")}" 123`, hub)), true);

    // ── (d) THE AUDITED LEAF WITH AN AGENT-CHOSEN DELEGATE → BLOCKED ──
    // This is the bypass a leaf-only pin admits: the rail executes
    // `$SELF_DIR/ci_exemption.py` (its own grader) and the shim executes
    // `$SELF_DIR/../verify-admin-merge-evidence.sh`, while the content walk is
    // skipped for the WHOLE invocation — so a pinned leaf is a launcher.
    const fwDelegate = join(work, "framework-forged-delegate");
    framework(fwDelegate);
    mkdirSync(join(fwDelegate, "scripts"), { recursive: true });
    installClosure(fwDelegate, { "scripts/ci_exemption.py": `#!/usr/bin/env python3\n${RESET}\n` });
    copyFileSync(RAIL, join(fwDelegate, "scripts", "admin-merge.sh")); // the AUDITED bytes
    expect("(d) the AUDITED rail bytes beside a REPLACED delegate (ci_exemption.py) → BLOCKED (the closure is the identity)",
      blocked(await bash(guard, `bash "${join(fwDelegate, "scripts", "admin-merge.sh")}" 123`, hub)), true);

    // ── (e) THE AUDITED LEAF WITH NO CLOSURE AT ALL → BLOCKED ──
    // Presence matters as much as bytes: declining only on a MISMATCH would
    // admit a root that omits the delegates entirely.
    const fwBare = join(work, "framework-bare");
    framework(fwBare);
    mkdirSync(join(fwBare, "scripts"), { recursive: true });
    copyFileSync(RAIL, join(fwBare, "scripts", "admin-merge.sh"));
    expect("(e) the AUDITED leaf with NO audited delegates present → BLOCKED (a missing delegate declines the exemption)",
      blocked(await bash(guard, `bash "${join(fwBare, "scripts", "admin-merge.sh")}" 123`, hub)), true);

    // ── MUTATIONS: each half must be load-bearing ──
    // M1 restores the literal-path equality this issue is about. If (a) still
    // passes under M1, the fix is inert and the suite is lying.
    const M1 = {
      name: "M1 literal-path-equality",
      from: "if (_sha256Of(real) !== want) continue;",
      to: "continue; // MUTATION M1: arm 2 disabled — literal-path equality restored",
    };
    const m1 = await loadGuard(join(work, "mut-m1"), M1);
    if (m1) {
      expect("(d1) MUTATION M1 — literal-path equality restored ⇒ (a) FAILS (the rail is blocked again)",
        blocked(await bash(m1, `bash "${RAIL}" --help`, hub)), true);
    }

    // M2 drops the digest. If (b) then passes, the content check was the only
    // thing refusing a renamed destructive script.
    const M2 = {
      name: "M2 no-identity-check",
      from: "if (_sha256Of(real) !== want) continue;",
      to: "if (false) continue; // MUTATION M2: the leaf's own bytes not compared",
    };
    const m2 = await loadGuard(join(work, "mut-m2"), M2);
    if (m2) {
      expect("(d2) MUTATION M2 — digest comparison dropped ⇒ (b) FAILS (a renamed destructive script is allowed)",
        blocked(await bash(m2, `bash "${join(fw2, "scripts", "admin-merge.sh")}" 123`, hub)), false);
    }

    // M3 drops the framework-root check. If (c) then passes, the root check is
    // the only thing keeping the exemption out of a session's own repo.
    const M3 = {
      name: "M3 no-root-check",
      from: "if (!_isFrameworkCheckout(root)) continue;",
      to: "if (false && !_isFrameworkCheckout(root)) continue; // MUTATION M3: framework-root check dropped",
    };
    const m3 = await loadGuard(join(work, "mut-m3"), M3);
    if (m3) {
      expect("(d3) MUTATION M3 — framework-root check dropped ⇒ (c3) FAILS (a non-framework directory is exempted)",
        blocked(await bash(m3, `bash "${join(plain, "scripts", "admin-merge.sh")}" 123`, hub)), false);
    }

    // M4 removes the WHOLE closure check (bytes AND presence), so the replaced-
    // delegate fixture (d) is admitted. The presence-only half is M5 below: an
    // absent delegate skipped instead of declining, which admits the bare-leaf
    // fixture (e). They are NOT duplicates — do not delete one.
    const M4 = {
      name: "M4 no-closure",
      from: "if (!_delegationClosurePinned(root, pin.delegates, rel)) continue;",
      to: "if (false) continue; // MUTATION M4: the delegation closure not verified",
    };
    const m4 = await loadGuard(join(work, "mut-m4"), M4);
    if (m4) {
      expect("(d5) MUTATION M4 — delegation closure not verified ⇒ (d) FAILS (a pinned leaf + a destructive delegate is allowed)",
        blocked(await bash(m4, `bash "${join(fwDelegate, "scripts", "admin-merge.sh")}" 123`, hub)), false);
    }

    // M5 drops only the delegate-PRESENCE half: an absent delegate is then
    // skipped instead of declining, so a root holding just the pinned leaf passes.
    const M5 = {
      name: "M5 missing-delegates-skipped",
      from: "    if (got === null) return false; // absent is not \"unverified\", it DECLINES",
      to: "    if (got === null) continue; // MUTATION M5: an absent delegate is skipped",
    };
    const m5 = await loadGuard(join(work, "mut-m5"), M5);
    if (m5) {
      expect("(d6) MUTATION M5 — an ABSENT delegate skipped instead of declining ⇒ (e) FAILS (a bare pinned leaf is admitted)",
        blocked(await bash(m5, `bash "${join(fwBare, "scripts", "admin-merge.sh")}" 123`, hub)), false);
    }
    // M6 drops the DIGEST from `_isAuditedSanctionedScript`. If (b3) then passes, the whole
    // stand-down rests on a path an agent can reproduce — which is the fail-open it replaced.
    const M6 = {
      name: "M6 body-arm-digest-dropped",
      // The anchor tracks the CURRENT body of `_isAuditedSanctionedScript`, re-cut on
      // 2026-10-24 when `bodyDigest` became a REQUIRED parameter and the disk-read fallback was
      // removed; the previous anchor (`got !== null && got === want`) no longer occurs there.
      // `deploy()` refuses to run a mutation whose anchor is absent (`fatal()` → nonzero exit),
      // so a stale anchor reds this suite rather than silently testing unmutated code — which
      // is why re-cutting it is a one-line maintenance task and not a silent hole.
      from: 'return typeof want === "string" && want.length === 64 && bodyDigest === want;',
      to: 'return true; // MUTATION M6: the body-arm digest dropped — the anchor alone grants',
    };
    const m6 = await loadGuard(join(work, "mut-m6"), M6);
    if (m6) {
      const m6Planted = plant(join(work, "mut-m6"));
      expect("(d7) MUTATION M6 — digest dropped from _isAuditedSanctionedScript ⇒ (b3) FAILS (unaudited bytes at a sanctioned relpath are admitted)",
        blocked(await bash(m6, `bash "${m6Planted}" --help`, hub)), false);
    }
  } finally {
    for (const [k, v] of savedEnv) { if (v === undefined) delete process.env[k]; else process.env[k] = v; }
    rmSync(work, { recursive: true, force: true });
  }
}

